"""Seed Bookora with demo preview content. Run: .venv/bin/python seed_preview.py"""
import os
import django

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "bookora.settings")
django.setup()

from django.contrib.auth.models import User
from django.core.files.base import ContentFile

from accounts.models import Profile
from feed.models import Post, ShortVideo, VideoComment, VideoLike
from shop.models import Ebook

# Clean demo data only (keeps other users untouched if re-run with same name)
User.objects.filter(username="bookora_demo").delete()

user = User.objects.create_user(username="bookora_demo", email="demo@bookora.example", password="demo12345")
profile, _ = Profile.objects.get_or_create(user=user)
profile.bio = "I write solo travel stories and share short book tips."
profile.link = "https://example.com/my-books"
profile.save()

# Cover + avatar via PIL
from PIL import Image, ImageDraw
import io

def png_bytes(color, text):
    img = Image.new("RGB", (600, 400), color)
    d = ImageDraw.Draw(img)
    d.text((30, 180), text, fill="white")
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()

profile.avatar.save("demo-avatar.png", ContentFile(png_bytes((124, 58, 237), "Bookora")), save=True)

ebook = Ebook.objects.create(
    author=user, title="Solo Travel, One Bag",
    description="A short guide to travelling solo — planning, safety, and packing light.",
    price="4.99",
)
ebook.cover.save("demo-cover.png", ContentFile(png_bytes((31, 41, 55), "Solo Travel")), save=True)
ebook.file.save("solo-travel-one-bag.pdf", ContentFile(b"%PDF-1.4 demo ebook"), save=True)

Post.objects.create(author=user, text="Hello Bookora! My new ebook is out — link in my bio. 📚")

# Short video is generated by ffmpeg in the shell step; this just ensures the file exists
video_path = "media/short_videos/demo-short.mp4"
if os.path.exists(video_path):
    video = ShortVideo.objects.create(author=user, caption="3 solo travel tips in 30 seconds ✈️")
    with open(video_path, "rb") as f:
        video.video.save("demo-short.mp4", ContentFile(f.read()), save=True)
    VideoLike.objects.create(user=user, video=video)
    VideoComment.objects.create(user=user, video=video, text="Loved tip 2! Saving this for my next trip.")
    print(f"Video: /videos/{video.pk}/")
else:
    print("No demo video file found at media/short_videos/demo-short.mp4 — skipping video")

print("Demo user: bookora_demo / demo12345")
print("Profile: /@bookora_demo/")
print("Ebook:", ebook.title, f"${ebook.price}")
